//! Embeds the repository's `data/` tree in the crate, so an installed `shprd`
//! finds its harness table, model catalogs, templates and skills without
//! `SHPRD_DATA_DIR` and without a checkout to read them from.
//!
//! The file list is generated rather than written by hand, so a file added to
//! `data/` is embedded by the next build and never silently left behind. Each
//! file goes in through `include_str!`, which also makes rustc rebuild this
//! crate when the file changes.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let Some(manifest) = std::env::var_os("CARGO_MANIFEST_DIR") else {
        panic!("CARGO_MANIFEST_DIR is not set: this script only runs under cargo");
    };
    let root = PathBuf::from(manifest).join("..").join("..").join("data");
    let mut files = Vec::new();
    walk(&root, "", &mut files);
    files.sort();
    if files.is_empty() {
        panic!(
            "the shipped data directory {} holds no file: the binary has nothing to find",
            root.display()
        );
    }
    // A directory's stamp alone misses a file edited in place, so every file is
    // named too.
    println!("cargo:rerun-if-changed={}", root.display());
    for (_, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    println!("cargo:rerun-if-changed=build.rs");

    let mut out = String::from(
        "// @generated by shprd-agents/build.rs: the shipped `data/` tree, embedded.\n\
         // One entry per file, by its name under `data/`.\n\
         pub(crate) const EMBEDDED: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &files {
        let _ = writeln!(
            out,
            "    ({name:?}, include_str!({:?})),",
            path.to_string_lossy()
        );
    }
    out.push_str("];\n");

    let Some(out_dir) = std::env::var_os("OUT_DIR") else {
        panic!("OUT_DIR is not set: this script only runs under cargo");
    };
    let target = PathBuf::from(out_dir).join("shipped_data.rs");
    if let Err(error) = std::fs::write(&target, out) {
        panic!("writing {}: {error}", target.display());
    }
}

/// Collects every file under `dir`, named relative to `root` with `/` between
/// the segments.
///
/// Hidden entries are skipped: a `.DS_Store` in the tree is not shipped data.
fn walk(root: &Path, prefix: &str, out: &mut Vec<(String, PathBuf)>) {
    let entries = match std::fs::read_dir(root) {
        Ok(entries) => entries,
        Err(error) => panic!("reading {}: {error}", root.display()),
    };
    for entry in entries {
        let Ok(entry) = entry else {
            continue;
        };
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.starts_with('.') {
            continue;
        }
        let path = entry.path();
        let relative = if prefix.is_empty() {
            name
        } else {
            format!("{prefix}/{name}")
        };
        if path.is_dir() {
            walk(&path, &relative, out);
        } else {
            out.push((relative, path));
        }
    }
}
