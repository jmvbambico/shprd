//! Embeds the repository's `host/herdr-desktop/` tree in the crate, so
//! `shprd install herdr-desktop` works from a binary with no checkout beside it
//! — the same way `shprd-agents/build.rs` embeds `data/`.
//!
//! Why it is needed at all: the installer used to resolve the tree from the
//! repository the caller was standing in (`~/projects/shprd/host/herdr-desktop`),
//! which is a checkout the person may not have, may not be the one that built
//! this binary, and is not where a worker's worktree is (the M10 gate's bug 6).
//! With the tree embedded, an installed `shprd` carries its own desktop.
//!
//! The file list is generated rather than written by hand, so a file added to
//! the host tree is embedded by the next build and never silently left behind.
//! Each file goes in through `include_bytes!`, which also makes rustc rebuild
//! this crate when it changes, and keeps every byte exactly as shipped.
//!
//! What is embedded is what the installer may install: `layouts/*.json`,
//! `mods/<name>/…` for every mod, and `keys.json` (read, not copied: its
//! bindings are merged into the person's). The tests and `bin/` scripts of the
//! host folder are not part of it.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let Some(manifest) = std::env::var_os("CARGO_MANIFEST_DIR") else {
        panic!("CARGO_MANIFEST_DIR is not set: this script only runs under cargo");
    };
    let root = PathBuf::from(manifest)
        .join("..")
        .join("..")
        .join("host")
        .join("herdr-desktop");
    let mut files = Vec::new();
    // The three shapes the installer knows, each walked on its own so the
    // generated list reads like the tree.
    walk(&root.join("layouts"), "layouts", &mut files);
    for entry in read_dir(&root.join("mods")) {
        if let Some(name) = entry.file_name().and_then(|name| name.to_str()) {
            walk(&entry, &format!("mods/{name}"), &mut files);
        }
    }
    let keys = root.join("keys.json");
    if keys.is_file() {
        files.push(("keys.json".to_string(), keys));
    }
    files.sort();
    if files.is_empty() {
        panic!(
            "the host tree {} holds no file: the binary has no desktop to install",
            root.display()
        );
    }
    // A directory's stamp alone misses a file edited in place, so every file is
    // named too.
    println!("cargo:rerun-if-changed={}", root.display());
    for (_, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
    }
    println!("cargo:rerun-if-changed=build.rs");

    let mut out = String::from(
        "// @generated by shprd/build.rs: the `host/herdr-desktop` tree, embedded.\n\
         // One entry per file, by its path under the host folder.\n\
         pub(crate) const HOST_FILES: &[(&str, &[u8])] = &[\n",
    );
    for (name, path) in &files {
        let _ = writeln!(
            out,
            "    ({name:?}, include_bytes!({:?})),",
            path.to_string_lossy()
        );
    }
    out.push_str("];\n");

    let Some(out_dir) = std::env::var_os("OUT_DIR") else {
        panic!("OUT_DIR is not set: this script only runs under cargo");
    };
    let target = PathBuf::from(out_dir).join("host_tree.rs");
    if let Err(error) = std::fs::write(&target, out) {
        panic!("writing {}: {error}", target.display());
    }
}

/// Every file under `dir`, named `<prefix>/<path>` with `/` between the
/// segments; hidden entries are skipped (an editor's droppings are not shipped).
fn walk(dir: &Path, prefix: &str, out: &mut Vec<(String, PathBuf)>) {
    for entry in read_dir(dir) {
        let Some(name) = entry.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        if name.starts_with('.') {
            continue;
        }
        let relative = format!("{prefix}/{name}");
        if entry.is_dir() {
            walk(&entry, &relative, out);
        } else {
            out.push((relative, entry));
        }
    }
}

/// Sorted directory entries; a directory that is not there is no entries.
fn read_dir(dir: &Path) -> Vec<PathBuf> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut paths: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok())
        .map(|e| e.path())
        .collect();
    paths.sort();
    paths
}
