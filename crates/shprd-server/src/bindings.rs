//! The TypeScript bindings: generated from the DTOs, never hand-written.
//!
//! The web app (`web/`) and any Herdr mod read the same shapes the service
//! answers with, so the types are generated from [`crate::dto`] into
//! `web/src/gen/`. Regenerate them with:
//!
//! ```text
//! cargo run -p shprd-server --example export-ts
//! ```
//!
//! The `bindings_are_current` test fails when the committed files are stale, so
//! a DTO change that forgets the regeneration cannot land.

use std::fs;
use std::path::{Path, PathBuf};

use crate::dto;
use crate::error::ServerError;

/// The header every generated file starts with.
pub const NOTE: &str = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n";

/// Where the generated bindings live, inside the repository.
pub fn bindings_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("web")
        .join("src")
        .join("gen")
}

/// The ts-rs configuration every export uses.
///
/// `number` for 64-bit integers because the shapes cross JSON, where a
/// JavaScript `bigint` cannot be deserialized from a JSON number.
pub fn config() -> ts_rs::Config {
    ts_rs::Config::new()
        .with_out_dir(bindings_dir())
        .with_large_int("number")
}

/// Writes every binding and the `index.ts` that re-exports them.
///
/// Returns the files it wrote, in the order it wrote them.
pub fn export(dir: &Path) -> Result<Vec<PathBuf>, ServerError> {
    let mut written = Vec::new();
    for (name, body) in generated()? {
        let path = dir.join(&name);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|err| ServerError::io(parent, err))?;
        }
        fs::write(&path, body).map_err(|err| ServerError::io(&path, err))?;
        written.push(path);
    }
    Ok(written)
}

/// The bindings `dir` is missing or has out of date.
///
/// Empty when every generated file is on disk with exactly the bytes this build
/// generates.
pub fn stale(dir: &Path) -> Result<Vec<String>, ServerError> {
    let mut stale = Vec::new();
    for (name, body) in generated()? {
        let path = dir.join(&name);
        match fs::read_to_string(&path) {
            Ok(existing) if existing == body => {}
            Ok(_) => stale.push(name),
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => stale.push(name),
            Err(err) => return Err(ServerError::io(path, err)),
        }
    }
    Ok(stale)
}

/// Every file's name and contents, including `index.ts`.
fn generated() -> Result<Vec<(String, String)>, ServerError> {
    let mut files = dto::exports()?;
    files.sort_by(|left, right| left.0.cmp(&right.0));
    let mut index = String::from(NOTE);
    index.push('\n');
    for (name, _) in &files {
        let stem = name.trim_end_matches(".ts");
        index.push_str(&format!("export * from \"./{stem}\";\n"));
    }
    files.push(("index.ts".to_string(), index));
    Ok(files)
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used)]

    use super::*;

    #[test]
    fn bindings_are_current() {
        let dir = bindings_dir();
        let stale = stale(&dir).expect("the bindings can be generated");
        assert!(
            stale.is_empty(),
            "web/src/gen is stale for {stale:?}; run `cargo run -p shprd-server --example export-ts`"
        );
    }

    #[test]
    fn exporting_into_a_fresh_directory_reproduces_the_commit() {
        // The CI gate runs `export-ts` and then `git diff --exit-code`; this is
        // the same check in miniature, so a stale file fails `cargo test` too.
        let dir = tempfile::tempdir().expect("a temp directory");
        let written = export(dir.path()).expect("the bindings are exportable");
        let committed = bindings_dir();
        let mut on_disk = 0;
        for entry in fs::read_dir(&committed).expect("web/src/gen reads") {
            let entry = entry.expect("a directory entry");
            let name = entry.file_name();
            let name = name.to_string_lossy().to_string();
            if !name.ends_with(".ts") {
                continue;
            }
            on_disk += 1;
            let fresh = fs::read(dir.path().join(&name)).expect("the export wrote it");
            let old = fs::read(committed.join(&name)).expect("the commit holds it");
            assert_eq!(
                fresh, old,
                "{name} is stale; run `cargo run -p shprd-server --example export-ts`"
            );
        }
        assert_eq!(
            written.len(),
            on_disk,
            "the export and the commit hold the same files"
        );
    }

    #[test]
    fn a_binding_names_its_imports() {
        // The snapshot is made of tasks, so its file must import them; a
        // generator that inlined or dropped the import would be caught here.
        let snapshot = fs::read_to_string(bindings_dir().join("SnapshotDto.ts"))
            .expect("SnapshotDto.ts is exported");
        assert!(snapshot.contains("import type { TaskDto }"));
        assert!(snapshot.contains("export type SnapshotDto"));
    }
}
